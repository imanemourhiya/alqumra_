// Generate a seat grid: 8 rows × 10 cols = 80 seats
export function generateSeats(sessionId) {
  const rows = ['A','B','C','D','E','F','G','H'];
  const leftCols  = [1, 2, 3, 4, 5, 6,];
  const rightCols = [ 7, 8, 9, 10, 11, 12];
  const allCols   = [...leftCols, ...rightCols];
  const occupied  = [3, 7, 12, 15, 22, 33, 44, 55, 63, 71];
  return rows.flatMap((row, ri) =>
    allCols.map((col, ci) => {
      const index = ri * allCols.length + ci;
      return {
        id: `${row}${col}`,
        row,
        col,
        block: col <= 6 ? 'left' : 'right',
        status: occupied.includes(index) ? 'occupied' : 'available',
        type: ri < 2 ? 'vip' : 'standard',
        price: ri < 2 ? 80 : 50,
      };
    })
  );
}

